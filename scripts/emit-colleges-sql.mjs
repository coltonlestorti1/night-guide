#!/usr/bin/env node
/**
 * Generates the `colleges` DDL + seed from src/data/colleges.ts, so the app's
 * picker and the database can never drift.
 *
 *   node scripts/emit-colleges-sql.mjs            — print to stdout
 *   node scripts/emit-colleges-sql.mjs --write    — write scripts/colleges-seed.sql
 *
 * Idempotent by design: re-running the emitted SQL after adding schools is
 * safe (create-if-not-exists + upsert on slug), so adding a college is
 * "edit the TS file, re-run this, re-paste".
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPTS = dirname(fileURLToPath(import.meta.url));
const REPO = join(SCRIPTS, "..");
const SOURCE = join(REPO, "src/data/colleges.ts");

/**
 * The source is TypeScript, so parse the literal rather than importing it —
 * this script must run under bare node with no build step.
 */
function parseColleges(ts) {
  const decl = ts.indexOf("export const COLLEGES: College[] = [");
  if (decl === -1) throw new Error("COLLEGES array not found in colleges.ts");
  // Seek past the `College[]` type annotation, or its brackets get matched
  // as the array literal and the body parses empty.
  const open = ts.indexOf("[", ts.indexOf("= [", decl));
  let depth = 0;
  let end = -1;
  for (let i = open; i < ts.length; i++) {
    if (ts[i] === "[") depth++;
    else if (ts[i] === "]") {
      depth--;
      if (depth === 0) {
        end = i;
        break;
      }
    }
  }
  if (end === -1) throw new Error("unterminated COLLEGES array");

  const body = ts.slice(open + 1, end);
  const rows = [];
  const entry = /\{\s*slug:\s*"([^"]+)",\s*name:\s*"([^"]+)",\s*city:\s*"([^"]+)",\s*state:\s*"([^"]+)",\s*region:\s*"([^"]+)"\s*\}/g;
  let m;
  while ((m = entry.exec(body)) !== null) {
    rows.push({ slug: m[1], name: m[2], city: m[3], state: m[4], region: m[5] });
  }
  return rows;
}

function parseRegionOrder(ts) {
  const start = ts.indexOf("export const REGION_ORDER");
  const open = ts.indexOf("{", start);
  const close = ts.indexOf("}", open);
  const order = {};
  for (const [, k, v] of ts.slice(open, close).matchAll(/(\w+):\s*(\d+)/g)) {
    order[k] = Number(v);
  }
  return order;
}

const q = (s) => `'${s.replace(/'/g, "''")}'`;

const ts = readFileSync(SOURCE, "utf8");
const colleges = parseColleges(ts);
const regionOrder = parseRegionOrder(ts);

const slugs = new Set();
for (const c of colleges) {
  if (slugs.has(c.slug)) throw new Error(`duplicate slug: ${c.slug}`);
  if (!(c.region in regionOrder)) throw new Error(`unknown region "${c.region}" on ${c.slug}`);
  slugs.add(c.slug);
}

const values = colleges
  .map(
    (c) =>
      `  (${q(c.slug)}, ${q(c.name)}, ${q(c.city)}, ${q(c.state)}, ${q(c.region)}, ${regionOrder[c.region]})`,
  )
  .join(",\n");

const sql = `-- Generated by scripts/emit-colleges-sql.mjs — do not hand-edit.
-- Source of truth: src/data/colleges.ts (${colleges.length} schools).
-- Safe to re-run: creates if absent, upserts every row on slug.

-- ---------- colleges ----------
-- Reference list backing the onboarding picker and profiles.college_slug.
-- slug (not uuid) is the key so the app's local list and this table stay
-- readable and diffable against each other. Slugs are permanent.

create table if not exists colleges (
  slug        text primary key,
  name        text not null,
  city        text not null,
  state       text not null,
  region      text not null,
  sort_order  integer not null default 70,
  created_at  timestamptz not null default now()
);

alter table colleges enable row level security;

-- Readable by anyone signed in; writes are seed-only (service role), same
-- posture as venues.
drop policy if exists "colleges readable by authenticated" on colleges;
create policy "colleges readable by authenticated"
  on colleges for select
  using (auth.role() = 'authenticated');

insert into colleges (slug, name, city, state, region, sort_order) values
${values}
on conflict (slug) do update set
  name       = excluded.name,
  city       = excluded.city,
  state      = excluded.state,
  region     = excluded.region,
  sort_order = excluded.sort_order;

-- ---------- profiles: college fields ----------
-- Both nullable: the onboarding step is optional and skippable, and a user
-- who skips can fill it in later from Edit profile.
-- on delete set null: removing a college row must never delete a profile.

alter table profiles add column if not exists college_slug text
  references colleges (slug) on update cascade on delete set null;

alter table profiles add column if not exists class_year smallint
  check (class_year is null or (class_year between 1950 and 2100));

comment on column profiles.college_slug is 'FK to colleges.slug. Null = not answered; the field is optional.';
comment on column profiles.class_year is 'Graduation year. class_year < current year means alum. Null = not answered.';

-- Supports "who else is from my school" without scanning profiles.
create index if not exists profiles_college_idx on profiles (college_slug) where college_slug is not null;
`;

if (process.argv.includes("--write")) {
  const out = join(SCRIPTS, "colleges-seed.sql");
  writeFileSync(out, sql);
  console.log(`wrote ${out} (${colleges.length} schools)`);
} else {
  process.stdout.write(sql);
}
